import { chromium, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import { gotoApp, fillLoginForm, submitLoginForm } from './lib/qaLogin.mjs';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await fs.mkdir('qa-artifacts', { recursive: true });
try {
  await gotoApp(page, process.env.PROTOTYPE_URL);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: '反馈', exact: true })).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.setViewportSize({ width: 1366, height: 768 });
  await page.getByRole('button', { name: '反馈', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: '查看反馈', exact: true })).toHaveCount(0);
  await expect(dialog.getByRole('button', { name: '提交反馈', exact: true })).toBeDisabled();
  await dialog.getByLabel('反馈内容').fill('试用建议：AI讲演增加倍速播放 <script>bad()</script>');
  await dialog.getByLabel('联系方式（选填）').fill('tester@example.com');
  await page.screenshot({ path: 'qa-artifacts/feedback-desktop.png' });
  await dialog.getByRole('button', { name: '提交反馈', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('反馈已提交');
  await dialog.getByRole('button', { name: '完成', exact: true }).click();
  await fillLoginForm(page, { username: 'admin', password: 'admin123' });
  await page.getByRole('tab', { name: '管理员', exact: true }).click();
  await submitLoginForm(page);
  await expect(page.locator('.profile-button')).toContainText('管理员');
  await expect(dialog.getByText('共 1 条反馈')).toBeVisible();
  await expect(dialog.locator('.feedback-content')).toContainText('<script>bad()</script>');
  await expect(dialog.getByText('tester@example.com')).toBeVisible();
  await expect(dialog.getByText('游客', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'qa-artifacts/feedback-admin.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await dialog.evaluate(node => { const rect = node.getBoundingClientRect(); return rect.left >= 0 && rect.right <= innerWidth; })).toBeTruthy();
  await expect(dialog.getByText('tester@example.com')).toBeVisible();
  await page.setViewportSize({ width: 1366, height: 768 });
  await dialog.getByRole('button', { name: '关闭反馈' }).click();
  await page.reload();
  await expect(page.locator('.profile-button')).toContainText('管理员');
  await page.getByRole('button', { name: '反馈', exact: true }).click();
  await expect(dialog.getByText('共 1 条反馈')).toBeVisible();
  await dialog.getByRole('button', { name: '关闭反馈' }).click();
  await page.locator('.profile-button').click();
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  await fillLoginForm(page, { username: 'teacher', password: 'ChangeMe123!' });
  await page.getByRole('tab', { name: '教师入口' }).click();
  await submitLoginForm(page);
  await expect(page.locator('.profile-button')).toBeVisible();
  await page.getByRole('button', { name: '反馈', exact: true }).click();
  await expect(dialog.getByRole('button', { name: '查看反馈', exact: true })).toHaveCount(0);
  const forbidden = await page.request.get(new URL('/api/admin/feedback', process.env.PROTOTYPE_URL).href);
  expect(forbidden.status()).toBe(403);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(dialog.getByLabel('反馈内容')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  expect(await dialog.evaluate(node => { const rect = node.getBoundingClientRect(); return rect.left >= 0 && rect.right <= innerWidth; })).toBeTruthy();
  await dialog.getByLabel('反馈内容').fill('手机试用反馈');
  await page.screenshot({ path: 'qa-artifacts/feedback-mobile.png' });
  await dialog.getByRole('button', { name: '提交反馈', exact: true }).click();
  await expect(dialog.getByRole('status')).toContainText('反馈已提交');
  expect(errors).toEqual([]);
  console.log('Feedback QA passed: guest submission, admin login/inbox/refresh, teacher authorization denial, mobile submission, literal HTML text.');
} finally { await browser.close(); }
