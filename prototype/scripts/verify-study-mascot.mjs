import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { gotoApp, fillLoginForm, submitLoginForm } from './lib/qaLogin.mjs';
const app=process.env.PROTOTYPE_APP_URL, live=process.env.QA_LIVE_AI==='1';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1366,height:900}}), errors=[];
page.on('pageerror',error=>errors.push(error.message));
const nav=label=>page.locator('.topbar-nav').getByRole('button',{name:label,exact:true});
try {
  await gotoApp(page,app); await fillLoginForm(page,{username:'demo2026001',password:'Student123!'}); await submitLoginForm(page);
  await nav('课后作业').click();
  const row=page.locator('.practice-question').first(); await expect(row).toBeVisible();
  await row.locator('.study-mascot-trigger').click();
  const dialog=page.locator('.study-mascot-dialog'); await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('button',{name:'发送到 DeepSeek'})).toBeDisabled();
  assert.ok(await dialog.locator('img').evaluate(img=>img.complete&&img.naturalWidth>0));
  await dialog.getByLabel('你的课程问题').fill('半加器与全加器有什么区别？请给一个输入例子。');
  const sent=page.waitForRequest(req=>req.url().endsWith('/api/student/study-assistant')&&req.method()==='POST');
  await dialog.getByRole('button',{name:'发送到 DeepSeek'}).click();
  const payload=(await sent).postDataJSON();
  assert.deepEqual(Object.keys(payload).sort(),['consent','context','question']);
  assert.deepEqual(Object.keys(payload.context).sort(),['chapterId','questionId']);
  assert.equal(payload.context.questionId,await row.getAttribute('data-qid'));
  await expect(dialog.locator('.study-mascot-source')).toHaveText(live?'AI 讲解 · DeepSeek':'AI 尚未配置 · 课程参考',{timeout:25000});
  await expect(dialog.locator('.study-mascot-check')).toBeVisible();
  await page.screenshot({path:'qa-artifacts/study-mascot-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  const bounds=await dialog.boundingBox(); assert.ok(bounds.x>=0&&bounds.x+bounds.width<=391);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:'qa-artifacts/study-mascot-mobile.png'});
  await page.keyboard.press('Escape'); await expect(dialog).toHaveCount(0);
  await nav('错题本').click(); await expect(page.locator('.mistakes-layout .study-mascot-trigger').first()).toBeVisible();
  await page.locator('.mistakes-layout .study-mascot-trigger').first().click(); await expect(dialog).toBeVisible();
  await dialog.getByRole('button',{name:'关闭小芯助教'}).click();
  await nav('课后作业').click();
  const triggers=page.locator('.study-mascot-trigger');
  await triggers.first().click(); await triggers.nth(1).focus(); await page.keyboard.press('Enter');
  await expect(dialog).toHaveCount(1);
  await dialog.getByRole('button',{name:'关闭小芯助教'}).click();
  await page.locator('.profile-button').click();
  await expect(page.locator('.profile-menu').getByRole('button')).toHaveCount(3);
  await page.getByRole('button',{name:'帮助支持',exact:true}).click();
  await page.getByRole('searchbox',{name:'搜索使用指南'}).fill('作业');
  await expect(page.locator('.help-step-guide').first()).toBeVisible();
  assert.ok(await page.locator('.help-step-guide ol li').count()>=3);
  assert.deepEqual(errors,[]);
  console.log('小芯验收通过：题目上下文、公开数据发送、'+(live?'真实 DeepSeek 讲解':'明确本地降级')+'、错题本、手机布局、键盘关闭和新手帮助');
}finally{await browser.close();}
