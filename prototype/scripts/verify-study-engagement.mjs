import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
import { createApp } from '../server/app.js';
import { openDatabase,createUser,createClass,addStudentToClass } from '../server/db.js';
import { hashPassword } from '../server/auth.js';
import { ASSIGNMENT_QUESTIONS } from '../src/assignmentQuestions.js';
import { saveAiConversation } from '../server/aiConversationRepository.js';
import { gotoApp,fillLoginForm,submitLoginForm } from './lib/qaLogin.mjs';

const artifacts=path.resolve('qa-artifacts/study-engagement');fs.mkdirSync(artifacts,{recursive:true});
const db=openDatabase(':memory:'),app=createApp({db,distDir:path.resolve('dist'),logger:()=>{},studyAssistantOptions:{env:{}}});
const password='Engagement-QA123!',passwordHash=await hashPassword(password);
const student=createUser(db,{username:'engagement-qa',displayName:'默契值测试学生',role:'student',passwordHash});
const teacher=createUser(db,{username:'engagement-teacher',displayName:'审核测试教师',role:'teacher',passwordHash});
const other=createUser(db,{username:'engagement-other',displayName:'另一位学生',role:'student',passwordHash});
const classroom=createClass(db,teacher.id,'默契值测试班');addStudentToClass(db,classroom.id,student.id);
const memoryId=saveAiConversation(db,{studentId:student.id,kind:'question',question:'补码如何计算？',answer:{source:'local',explanation:'公开课程参考'},context:{conceptId:'concept-twos-complement'}});
db.prepare('UPDATE ai_conversations SET created_at=? WHERE id=?').run(new Date(Date.now()-60000).toISOString(),memoryId);
const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
const base=`http://127.0.0.1:${server.address().port}`,browser=await chromium.launch({headless:true}),errors=[];
try {
  const page=await browser.newPage({viewport:{width:1366,height:900}});page.on('pageerror',e=>errors.push(e.message));
  async function login(user){await gotoApp(page,base);await fillLoginForm(page,{username:user.username,password});if(user.role==='teacher')await page.locator('[data-login-role="teacher"]').click();await submitLoginForm(page);await page.locator('.profile-button').waitFor();}
  async function logout(){await page.request.post(base+'/api/auth/logout');await page.reload();}
  await login(student);
  await page.getByTestId('study-recommendations').getByTestId('study-engagement').waitFor();
  await page.getByRole('button',{name:'课后作业',exact:true}).click();
  const q=ASSIGNMENT_QUESTIONS.find(q=>q.chapterId==='ch1'&&q.type==='choice');
  const card=page.locator(`[data-qid="${q.id}"]`);await card.waitFor();await card.scrollIntoViewIfNeeded();
  await page.waitForTimeout(1100);
  await card.locator('input[type="radio"]').evaluateAll((inputs,value)=>inputs.find(el=>el.parentElement.textContent.trim()===value).click(),q.answer);
  await page.getByRole('button',{name:'提交并判分',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.study-sync-status')?.textContent.includes('已同步'));
  const attempt=db.prepare('SELECT * FROM chapter_practice_attempts WHERE student_id=? ORDER BY id DESC LIMIT 1').get(student.id);
  const timing=JSON.parse(attempt.observations_json)[q.id];assert(timing.visibleActiveMs>=900);assert(timing.firstAnswerMs>=900);assert(timing.answerActiveMs>=0);
  await page.getByRole('button',{name:'提交并判分',exact:true}).click();
  await page.waitForTimeout(250);assert.equal(db.prepare('SELECT count(*) n FROM chapter_practice_attempts WHERE student_id=?').get(student.id).n,1);
  await page.locator('.study-companion-trigger').click();
  const companion=page.locator('.study-companion-dialog');await companion.getByTestId('study-engagement').waitFor();
  await companion.getByText('本次答疑选取小芯记忆',{exact:false}).click();
  await companion.locator('.companion-memory-select input').first().check();
  await companion.getByLabel('你的课程问题').fill('补码表示的规则是什么？');
  const sent=page.waitForRequest(r=>r.url().endsWith('/api/student/study-assistant')&&r.method()==='POST');
  await companion.getByRole('button',{name:'询问助教'}).click();
  const payload=(await sent).postDataJSON();assert.deepEqual(payload.memoryIds,[memoryId]);assert.equal(payload.memoryConsent,'selected-course-questions');
  await page.waitForFunction(()=>!document.querySelector('#companion-question').disabled);
  assert.equal(await companion.locator('.companion-memory-select input:checked').count(),0);
  await page.getByRole('button',{name:'关闭小芯助教'}).click();
  console.log('PASS observed per-question timing, frozen replay, local memory and per-question selection');
  await logout();await login(teacher);await page.getByRole('button',{name:'学习记录',exact:true}).click();
  const review=page.getByTestId('teacher-engagement-review');await review.waitFor();await review.getByLabel('平时加分上限').fill('5');
  for(const label of ['任务天数目标','不同题目目标','不同实验目标','后续行动目标'])await review.getByLabel(label,{exact:true}).fill('1');
  await review.getByRole('button',{name:'保存班级加分规则'}).click();
  await review.getByText('班级规则已保存',{exact:false}).waitFor();
  const row=review.locator(`[data-engagement-student="${student.id}"]`);
  await row.getByText('查看实验与答题时间',{exact:true}).click();
  await row.getByRole('button',{name:'审核并确认加分',exact:true}).click();
  await row.getByText('已确认 +2.5 分',{exact:true}).waitFor();
  assert.equal(db.prepare('SELECT count(*) n FROM study_bonus_reviews').get().n,1);
  await review.screenshot({path:path.join(artifacts,'teacher.png')});
  const download=page.waitForEvent('download');await review.getByRole('button',{name:'导出加分明细'}).click();await(await download).saveAs(path.join(artifacts,'bonus.csv'));
  assert.match(fs.readFileSync(path.join(artifacts,'bonus.csv'),'utf8'),/engagement-qa/);
  await page.getByLabel('学情查看对象').selectOption('mine');await review.waitFor({state:'detached'});
  await logout();await login(student);
  const own=page.getByTestId('study-recommendations').getByTestId('study-engagement');await own.waitFor();await own.getByText('老师已确认的平时加分').click();await own.getByText('默契值测试班：+2.5 分',{exact:false}).waitFor();
  await page.setViewportSize({width:390,height:844});await own.scrollIntoViewIfNeeded();assert(await own.evaluate(el=>el.getBoundingClientRect().right<=innerWidth+1));await own.screenshot({path:path.join(artifacts,'student-mobile.png')});
  await logout();await login(other);await page.getByTestId('study-recommendations').getByTestId('study-engagement').waitFor();assert.equal(await page.getByText('老师已确认的平时加分').count(),0);
  console.log('PASS teacher class cap, evidence review, confirmation/export, teacher trial and student isolation, narrow screen');
  assert.deepEqual(errors,[]);fs.writeFileSync(path.join(artifacts,'result.json'),JSON.stringify({pass:true,errors,checks:10},null,2));
}finally{await browser.close();await new Promise(r=>{server.close(r);server.closeAllConnections();});db.close();}
