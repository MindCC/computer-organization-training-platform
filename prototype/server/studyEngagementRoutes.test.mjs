import test from 'node:test';
import assert from 'node:assert/strict';
import { createApp } from './app.js';
import { openDatabase,createUser,createClass,addStudentToClass,grantClassAccess } from './db.js';
import { hashPassword } from './auth.js';
import { ASSIGNMENT_QUESTIONS } from '../src/assignmentQuestions.js';
import { saveAiConversation } from './aiConversationRepository.js';
import { selectedStudyMemory } from './studyEngagement.js';
import { studyAssistantMessages } from './studyAssistant.js';

test('engagement routes protect accounts, shared class access, memory selection, time idempotency, and bonus audit',async()=>{
  const db=openDatabase(':memory:'),app=createApp({db,serveStatic:false,logger:()=>{},studyAssistantOptions:{env:{}}});
  const password='Engagement-Test123!',passwordHash=await hashPassword(password);
  const users={};
  for(const [username,role,profile] of [['owner','teacher',{}],['shared','teacher',{}],['outsider','teacher',{}],['learner','student',{}],['other','student',{}],['readonly','student',{demoAccount:true}]])users[username]=createUser(db,{username,role,displayName:username,passwordHash,profile});
  const classroom=createClass(db,users.owner.id,'Review'),classId=classroom.id;
  addStudentToClass(db,classId,users.learner.id);grantClassAccess(db,classId,users.shared.id);
  const memoryId=saveAiConversation(db,{studentId:users.learner.id,kind:'question',question:'补码如何计算',answer:{source:'local'},context:{conceptId:'concept-twos-complement'}});
  const rejectedId=saveAiConversation(db,{studentId:users.learner.id,kind:'question',question:'无关问题',answer:{reason:'COURSE_SCOPE_REJECTED'}});
  assert.throws(()=>selectedStudyMemory(db,users.other.id,[memoryId],'selected-course-questions'),/不存在/);
  assert.throws(()=>selectedStudyMemory(db,users.learner.id,[memoryId]),/明确选择/);
  assert.throws(()=>selectedStudyMemory(db,users.learner.id,[rejectedId],'selected-course-questions'),/不存在/);
  const memory=selectedStudyMemory(db,users.learner.id,[memoryId],'selected-course-questions');
  assert.deepEqual(Object.keys(memory[0]).sort(),['question','topic']);
  assert(!studyAssistantMessages('补码是什么',{})[0].content.includes('补码如何计算'));
  assert(studyAssistantMessages('补码是什么',{},memory)[0].content.includes('补码如何计算'));
  const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const base=`http://127.0.0.1:${server.address().port}`;
  const req=async(path,cookie,body)=>{const r=await fetch(base+path,{method:body?'POST':'GET',headers:{...(cookie?{cookie}:{}),...(body?{'content-type':'application/json'}:{})},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,cookie:r.headers.get('set-cookie')?.split(';')[0],data:r.headers.get('content-type').includes('json')?await r.json():await r.text()};};
  try {
    const cookies={};for(const username of Object.keys(users))cookies[username]=(await req('/api/auth/login',null,{username,password})).cookie;
    const own='/api/student/study-engagement',teacherBase=`/api/teacher/classes/${classId}/study-engagement`;
    assert.equal((await req(own)).status,401);assert.equal((await req(own,cookies.owner)).status,403);
    assert.equal((await req(own+'?studentId='+users.learner.id,cookies.other)).data.memory.length,0);
    assert.equal((await req(own+'/visit',cookies.readonly,{})).status,403);
    assert.equal((await req(teacherBase,cookies.outsider)).status,403);
    assert.equal((await req(teacherBase,cookies.shared)).data.canManage,false);
    const date=new Date(Date.now()+8*3600000).toISOString().slice(0,10);
    const policy={startDate:date,endDate:date,bonusCap:5,dayTarget:1,questionTarget:1,labTarget:1,followThroughTarget:1};
    assert.equal((await req(teacherBase+'/policy',cookies.shared,policy)).status,403);
    assert.equal((await req(teacherBase+'/policy',cookies.owner,policy)).status,200);
    assert.equal((await req(teacherBase+'/policy',cookies.owner,{...policy,startDate:'2026-99-99'})).status,400);
    const q=ASSIGNMENT_QUESTIONS.find(q=>q.type==='choice');
    const body={chapterId:q.chapterId,answers:{[q.id]:q.answer},clientSubmissionId:crypto.randomUUID(),observations:{[q.id]:{visibleActiveMs:2000,firstAnswerMs:1000,inputChanges:1,score:100}}};
    assert.equal((await req('/api/student/chapter-practice',cookies.learner,body)).status,201);
    assert.equal((await req('/api/student/chapter-practice',cookies.learner,body)).status,200);
    assert.equal((await req('/api/student/chapter-practice',cookies.learner,{...body,observations:{[q.id]:{visibleActiveMs:3000,firstAnswerMs:1000}}})).status,409);
    const row=(await req(teacherBase,cookies.owner)).data.students[0];assert.equal(row.timings.length,1);assert.equal(row.timings[0].score,undefined);
    const confirmation={studentId:users.learner.id,bonus:row.suggestedBonus,reason:'',reviewToken:row.reviewToken,clientSubmissionId:crypto.randomUUID()};
    assert.equal((await req(teacherBase+'/confirm',cookies.shared,confirmation)).status,403);
    assert.equal((await req(teacherBase+'/confirm',cookies.owner,{...confirmation,studentId:users.other.id})).status,404);
    assert.equal((await req(teacherBase+'/confirm',cookies.owner,confirmation)).status,200);
    assert.equal((await req(own,cookies.learner)).data.confirmedBonuses[0].bonus,row.suggestedBonus);
    assert.equal((await req(own,cookies.other)).data.confirmedBonuses.length,0);
    assert.match((await req(teacherBase+'/export.csv',cookies.owner)).data,/learner/);
    assert.equal(db.prepare("SELECT count(*) n FROM audit_logs WHERE action='study_bonus_confirmed'").get().n,1);
    assert.equal((await req('/api/student/study-assistant',cookies.other,{question:'补码是什么',consent:'deepseek-public-question',memoryIds:[memoryId],memoryConsent:'selected-course-questions'})).status,404);
  }finally{await new Promise(r=>{server.close(r);server.closeAllConnections();});db.close();}
});
